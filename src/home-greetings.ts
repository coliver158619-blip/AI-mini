// Read the device clock on each tap, including when a room stays open overnight.
export function greetingPeriod(date = new Date()) {
 const hour = date.getHours();
 return hour < 5 || hour >= 23 ? 'late' : hour < 11 ? 'morning' : hour < 14 ? 'noon' : hour < 18 ? 'afternoon' : 'evening';
}

