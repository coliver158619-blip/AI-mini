export function randomHomeGreeting(recent: readonly string[], date = new Date()) {
 const pool = greetings[greetingPeriod(date)];
 const choices = pool.filter(text => !recent.slice(-6).includes(text));
 return choices[Math.floor(Math.random() * choices.length)];
}
